import assert from 'node:assert/strict';
import {standardPower,entityInfo,comparePower,savedPower,fusionPower,powerLabel,stageForms} from '../src/power';
const g=(era:string,state='Super Saiyan')=>({name:'Goku',era,state});
const namek=g('DBZ · Namek / Frieza'), cell=g('DBZ · Cell'), buu=g('DBZ · Majin Buu'), superG=g('DBS · Giải đấu Sức mạnh');
assert.equal(powerLabel(standardPower(namek)),'100.0 PI');
assert.ok(standardPower(namek).logPower!<standardPower(cell).logPower!);
assert.ok(standardPower(cell).logPower!<standardPower(buu).logPower!);
assert.ok(standardPower(buu).logPower!<standardPower(superG).logPower!);
assert.ok(standardPower(g(superG.era,'Super Saiyan Blue')).logPower!>standardPower(superG).logPower!);
assert.equal(standardPower(g(namek.era,'Ultra Instinct')).logPower,null);
assert.equal(standardPower(g(cell.era,'Super Saiyan 2')).logPower,null);
assert.ok(!stageForms('Vegeta','DBZ · Majin Buu').includes('Super Saiyan 3'));
const a=entityInfo(namek,[]),b=entityInfo(superG,[]),ab=comparePower(a,b),ba=comparePower(b,a);
assert.equal(ab.winnerChar,2);assert.equal(ba.winnerChar,1);assert.equal(ab.prob1,ba.prob2);assert.equal(ab.expectedWinner,ba.expectedWinner);
assert.ok(ab.expectedWinner.includes(superG.era));
assert.equal(comparePower(a,a).winnerChar,0);assert.equal(comparePower(a,a).prob1,50);
const unknown=entityInfo({name:'Uncatalogued',era:'x',state:'Base'},[]);
assert.equal(comparePower(a,unknown).known,false);
assert.equal(comparePower(a,entityInfo({name:'Zeno',era:'Dragon Ball Super',state:'Base'},[])).known,false);
const old={id:'old',name:'Saved Goku',powerLevel:1e99,level:1e99,rank:'CHAOS',imageUrl:'original',baseCharacters:[namek]};
const before=JSON.stringify(old);assert.equal(savedPower(old,[old]).logPower,0);assert.equal(JSON.stringify(old),before);
assert.equal(fusionPower([namek],[]).logPower,0);
assert.ok(fusionPower([namek,cell],[]).logPower!>standardPower(cell).logPower!);
assert.equal(fusionPower([{name:'Unknown item',era:'x',state:'x'},namek],[]).logPower,null);
const loop={id:'cycle',baseCharacters:[{...namek,fusionId:'cycle'}]};assert.equal(savedPower(loop,[loop]).logPower,null);
const missing=entityInfo({...namek,fusionId:'deleted'},[]);assert.equal(missing.powerProfile.logPower,null);
console.log('PASS: era progression, forms, symmetry, ties, unknowns, legacy migration, fusion, cyclic/missing references.');
console.log([namek,cell,buu,superG].map(c=>[c.era,powerLabel(standardPower(c))]));
